CREATE TABLE operator_action (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app_user,
    action text NOT NULL,
    target_id bigint,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

