-- Jobs, checkpoints and operator instructions survive API/worker restarts.
ALTER TABLE feed_source
    ADD COLUMN game_code text REFERENCES game,
    ADD COLUMN label text,
    ADD COLUMN interval_seconds integer NOT NULL DEFAULT 3600 CHECK (interval_seconds >= 60),
    ADD COLUMN state text NOT NULL DEFAULT 'IDLE' CHECK (state IN ('IDLE','RUNNING','OK','ERROR','BLOCKED')),
    ADD COLUMN last_started_at timestamptz,
    ADD COLUMN last_finished_at timestamptz,
    ADD COLUMN last_success_at timestamptz,
    ADD COLUMN last_error_at timestamptz,
    ADD COLUMN last_error text,
    ADD COLUMN last_seen integer NOT NULL DEFAULT 0,
    ADD COLUMN last_added integer NOT NULL DEFAULT 0,
    ADD COLUMN failure_count integer NOT NULL DEFAULT 0,
    ADD COLUMN requested_at timestamptz,
    ADD COLUMN retry_after_at timestamptz;
CREATE INDEX feed_due ON feed_source(next_fetch_at) WHERE enabled;

ALTER TABLE card ADD COLUMN source_id bigint REFERENCES feed_source, ADD COLUMN source_url text;
CREATE INDEX card_source ON card(source_id) WHERE source_id IS NOT NULL;
ALTER TABLE feed_item ADD COLUMN source_published_at timestamptz;
CREATE INDEX news_timeline ON feed_item(status,(coalesce(source_published_at,collected_at)) DESC,id DESC)
    WHERE payload->>'kind'='NEWS';
CREATE TABLE worker_heartbeat (
    id text PRIMARY KEY,
    seen_at timestamptz,
    started_at timestamptz,
    restart_requested_at timestamptz,
    restart_count integer NOT NULL DEFAULT 0
);
