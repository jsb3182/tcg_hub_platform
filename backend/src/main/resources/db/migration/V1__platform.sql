CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE CHECK (email = lower(trim(email))),
    password_hash text NOT NULL,
    role text NOT NULL DEFAULT 'ROLE_USER' CHECK (role IN ('ROLE_USER','ROLE_ADMIN')),
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE refresh_session (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app_user ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX refresh_expiry ON refresh_session(expires_at);
CREATE INDEX refresh_user ON refresh_session(user_id);

CREATE TABLE pack (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_code text NOT NULL REFERENCES game,
    name text NOT NULL,
    code text,
    release_date date,
    release_label text,
    banner_key text,
    metadata jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(metadata) = 'object'),
    legacy_key text UNIQUE,
    UNIQUE (game_code, id)
);
CREATE TABLE image_sheet (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key text NOT NULL UNIQUE,
    cell_width integer NOT NULL CHECK (cell_width > 0),
    cell_height integer NOT NULL CHECK (cell_height > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE card (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_code text NOT NULL REFERENCES game,
    pack_id bigint,
    name text NOT NULL,
    original_name text,
    number text,
    rarity text,
    effect text,
    release_date date,
    specs jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(specs) = 'object'),
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PUBLISHED','REJECTED')),
    legacy_key text UNIQUE,
    UNIQUE (game_code, id),
    FOREIGN KEY (game_code, pack_id) REFERENCES pack (game_code, id)
);
CREATE INDEX card_catalog ON card(game_code, id) WHERE status = 'PUBLISHED';
CREATE INDEX card_pack ON card(pack_id);
CREATE TABLE card_variant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id bigint NOT NULL REFERENCES card ON DELETE CASCADE,
    position integer NOT NULL DEFAULT 0 CHECK (position >= 0),
    rarity text,
    sheet_id bigint REFERENCES image_sheet,
    col_idx smallint CHECK (col_idx BETWEEN 0 AND 3),
    row_idx smallint CHECK (row_idx BETWEEN 0 AND 2),
    CHECK (num_nonnulls(sheet_id, col_idx, row_idx) IN (0,3)),
    UNIQUE (card_id, position)
);
CREATE TABLE media_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id bigint NOT NULL REFERENCES card_variant ON DELETE CASCADE,
    input_hash text NOT NULL,
    spool_key text UNIQUE,
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','DONE','FAILED')),
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);
CREATE INDEX media_ready ON media_job(id) WHERE status = 'PENDING';
CREATE INDEX media_latest ON media_job(variant_id, id DESC);
CREATE INDEX media_cleanup ON media_job(id) WHERE status <> 'PENDING' AND spool_key IS NOT NULL;

CREATE TABLE store (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    address text NOT NULL,
    location geography(Point,4326) NOT NULL,
    hours jsonb NOT NULL DEFAULT '{}',
    directions_url text
);
CREATE INDEX store_location_gist ON store USING gist(location);
CREATE TABLE store_game (
    store_id bigint REFERENCES store ON DELETE CASCADE,
    game_code text REFERENCES game,
    PRIMARY KEY(store_id, game_code)
);
CREATE TABLE favorite_store (
    user_id bigint REFERENCES app_user ON DELETE CASCADE,
    store_id bigint REFERENCES store ON DELETE CASCADE,
    PRIMARY KEY(user_id, store_id)
);
CREATE TABLE feed_source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider text NOT NULL,
    source_key text NOT NULL,
    store_id bigint REFERENCES store,
    auto_publish boolean NOT NULL DEFAULT false,
    enabled boolean NOT NULL DEFAULT true,
    cursor_value text,
    next_fetch_at timestamptz,
    UNIQUE(provider, source_key)
);
CREATE TABLE feed_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES feed_source,
    external_id text NOT NULL,
    source_url text NOT NULL,
    payload jsonb NOT NULL,
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PUBLISHED','REJECTED')),
    card_id bigint REFERENCES card,
    reviewer_id bigint REFERENCES app_user ON DELETE SET NULL,
    collected_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(source_id, external_id)
);
CREATE INDEX feed_review ON feed_item(collected_at) WHERE status = 'PENDING';
CREATE TABLE calendar_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id bigint REFERENCES store ON DELETE CASCADE,
    owner_id bigint REFERENCES app_user ON DELETE CASCADE,
    game_code text REFERENCES game,
    feed_item_id bigint REFERENCES feed_item,
    source_event_key text,
    title text NOT NULL,
    category text NOT NULL CHECK (category IN ('NOTICE','TOURNAMENT','RESTOCK','PERSONAL')),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz,
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PUBLISHED','REJECTED')),
    CHECK ((category = 'PERSONAL' AND owner_id IS NOT NULL) OR
           (category <> 'PERSONAL' AND store_id IS NOT NULL AND owner_id IS NULL)),
    CHECK (ends_at IS NULL OR ends_at >= starts_at),
    CHECK ((feed_item_id IS NULL) = (source_event_key IS NULL)),
    UNIQUE(feed_item_id, source_event_key)
);
CREATE INDEX calendar_store_time ON calendar_event(store_id, starts_at);
CREATE INDEX calendar_owner_time ON calendar_event(owner_id, starts_at);
CREATE TABLE event_reminder (
    user_id bigint REFERENCES app_user ON DELETE CASCADE,
    event_id bigint REFERENCES calendar_event ON DELETE CASCADE,
    remind_at timestamptz NOT NULL,
    delivered_at timestamptz,
    PRIMARY KEY(user_id, event_id, remind_at)
);
CREATE INDEX reminder_due ON event_reminder(remind_at) WHERE delivered_at IS NULL;

CREATE TABLE price_listing (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id bigint NOT NULL REFERENCES card_variant ON DELETE CASCADE,
    provider text NOT NULL,
    external_key text NOT NULL,
    source_url text,
    next_fetch_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(provider, external_key)
);
CREATE INDEX price_due ON price_listing(next_fetch_at);
CREATE TABLE price_snapshot (
    listing_id bigint REFERENCES price_listing ON DELETE CASCADE,
    observed_at timestamptz NOT NULL,
    currency char(3) NOT NULL DEFAULT 'KRW',
    amount numeric(16,2) NOT NULL CHECK (amount >= 0),
    PRIMARY KEY(listing_id, observed_at)
);

CREATE TABLE deck (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES app_user ON DELETE CASCADE,
    game_code text NOT NULL REFERENCES game,
    name text NOT NULL,
    format text NOT NULL,
    share_token uuid UNIQUE,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(game_code,id)
);
CREATE TABLE deck_entry (
    deck_id bigint NOT NULL,
    game_code text NOT NULL,
    card_id bigint NOT NULL,
    section text NOT NULL,
    quantity smallint NOT NULL CHECK (quantity > 0),
    PRIMARY KEY(deck_id,section,card_id),
    FOREIGN KEY (game_code,deck_id) REFERENCES deck(game_code,id) ON DELETE CASCADE,
    FOREIGN KEY (game_code,card_id) REFERENCES card(game_code,id)
);

CREATE TABLE board_post (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES app_user,
    board text NOT NULL CHECK (board IN ('FREE','SUGGESTION','TRADE')),
    title text NOT NULL,
    body text NOT NULL,
    trade_type text CHECK (trade_type IN ('SELL','BUY','EXCHANGE')),
    trade_status text CHECK (trade_status IN ('OPEN','RESERVED','CLOSED')),
    CHECK ((board='TRADE' AND trade_type IS NOT NULL AND trade_status IS NOT NULL)
        OR (board<>'TRADE' AND trade_type IS NULL AND trade_status IS NULL)),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX board_timeline ON board_post(board,id DESC);
CREATE TABLE post_card (
    post_id bigint REFERENCES board_post ON DELETE CASCADE,
    card_id bigint REFERENCES card,
    PRIMARY KEY(post_id,card_id)
);
CREATE TABLE post_comment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL REFERENCES board_post ON DELETE CASCADE,
    author_id bigint NOT NULL REFERENCES app_user,
    parent_id bigint,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(post_id,id),
    CHECK (parent_id IS NULL OR parent_id <> id),
    FOREIGN KEY(post_id,parent_id) REFERENCES post_comment(post_id,id) ON DELETE CASCADE
);
CREATE TABLE abuse_report (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id bigint NOT NULL REFERENCES app_user,
    post_id bigint REFERENCES board_post ON DELETE CASCADE,
    comment_id bigint REFERENCES post_comment ON DELETE CASCADE,
    reason text NOT NULL,
    status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(post_id,comment_id)=1),
    UNIQUE(reporter_id,post_id),
    UNIQUE(reporter_id,comment_id)
);
