"""Rebuild V30 from the pinned public artwork manifest without downloading card images."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

REVISION = "433fe3d2223d3453b7732b5bad016196fb7b092f"
DIGEST = "86933497cb03bcf6dd4826549f586a4aa6d9863b8296e0b4775095c867b78f22"
HOSTS = {"ko": "artworks-ko-db.ygoresources.com", "en": "artworks-en-n.ygoresources.com",
         "ja": "artworks-jp-n.ygoresources.com"}
PATH = re.compile(r"/(\d+)/(\d+)/(\d+)_(\d+)\.png", re.ASCII)


def references(cards):
    for cid, versions in sorted(cards.items(), key=lambda pair: int(pair[0])):
        if not re.fullmatch(r"[1-9][0-9]{0,8}", cid):
            raise ValueError("Unexpected card identity")
        paths = {}
        rush = False
        for artwork, version in sorted(versions.items(), key=lambda pair: int(pair[0])):
            for lang, host in HOSTS.items():
                for entry in version.get("idx", {}).get(lang, []):
                    url = urlsplit(entry["path"])
                    if url.hostname == "artworks-jp-rn.ygoresources.com":
                        rush = True
                    if url.hostname != host:
                        continue
                    match = PATH.fullmatch(url.path)
                    if (not match or url.scheme not in ("", "https") or url.netloc != host or url.query
                            or url.fragment or not re.fullmatch(r"[1-9][0-9]{0,3}", artwork)):
                        raise ValueError("Unexpected regional artwork mapping")
                    high, middle, low, image_id = map(int, match.groups())
                    if middle >= 100 or low >= 100 or high * 10000 + middle * 100 + low != int(cid) or image_id != int(artwork):
                        raise ValueError("Artwork path disagrees with the upstream identity")
                    # A regional card reference is the lowest explicitly present artwork number.
                    paths.setdefault(lang, url.path)
        if paths and not rush:
            yield cid, paths


def generate(manifest, output):
    data = manifest.read_bytes()
    if hashlib.sha256(data).hexdigest() != DIGEST:
        raise ValueError("Expected the pinned YGOResources manifest")
    rows = []
    for cid, paths in references(json.loads(data)["cards"]):
        values = [f"'{paths[lang]}'" if lang in paths else "NULL" for lang in HOSTS]
        rows.append("(" + ",".join([f"'{cid}'", *values]) + ")")
    header = f"""-- Generated by frontend/tools/build-yugioh-reference-art.py
-- yugioh-artworks/artworks-index {REVISION}, SHA-256 {DIGEST}
-- Each locale is a card-level artwork reference. Individual pack printings and atlas tiles are independent.
CREATE TABLE yugioh_reference_art (
    cid text PRIMARY KEY CHECK (cid ~ '^[1-9][0-9]{{0,8}}$'),
    ko_path text, en_path text, ja_path text,
    CHECK (num_nonnulls(ko_path,en_path,ja_path)>0)
);
INSERT INTO yugioh_reference_art(cid,ko_path,en_path,ja_path) VALUES
"""
    with output.open("w", encoding="utf-8", newline="\n") as f:
        f.write(header + ",\n".join(rows) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.manifest, args.output)
