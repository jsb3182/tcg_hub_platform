CREATE TABLE product_release (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_code text NOT NULL REFERENCES game,
    product_key text NOT NULL CHECK (length(product_key) BETWEEN 1 AND 160),
    region text NOT NULL CHECK (region IN ('KR','JP','NA','EN','EU','GLOBAL','CN','TCG')),
    code text,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 400),
    names jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(names)='object'),
    release_date date NOT NULL,
    source_url text NOT NULL,
    catalog_code text,
    catalog_name text,
    from_seed boolean NOT NULL DEFAULT false,
    UNIQUE(game_code,product_key,region)
);
CREATE INDEX product_release_chronology ON product_release(release_date,id);
CREATE INDEX product_release_game_chronology ON product_release(game_code,release_date,id);
CREATE INDEX pack_calendar_code ON pack(game_code,upper(code));
CREATE INDEX pack_calendar_name ON pack(game_code,lower(name));

