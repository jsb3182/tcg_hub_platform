CREATE TABLE catalog_art_file (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_code text NOT NULL REFERENCES game(code),
    source_url text NOT NULL UNIQUE CHECK (length(source_url) BETWEEN 12 AND 2048),
    storage_key text CHECK (storage_key ~ '^cards/[0-9a-f]{64}\.webp$'),
    source_sha256 text CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    checked_at timestamptz,
    next_attempt timestamptz NOT NULL DEFAULT now(),
    failures integer NOT NULL DEFAULT 0 CHECK (failures >= 0),
    last_error text
);
CREATE INDEX catalog_art_due ON catalog_art_file(game_code,next_attempt,id);
CREATE INDEX catalog_art_storage ON catalog_art_file(storage_key) WHERE storage_key IS NOT NULL;
CREATE TABLE catalog_art_card (
    card_id bigint NOT NULL REFERENCES card(id) ON DELETE CASCADE,
    file_id bigint NOT NULL REFERENCES catalog_art_file(id) ON DELETE CASCADE,
    PRIMARY KEY(card_id,file_id)
);
CREATE INDEX catalog_art_links ON catalog_art_card(file_id,card_id);
CREATE TABLE catalog_art_scan (
    game_code text PRIMARY KEY REFERENCES game(code), after_id bigint NOT NULL DEFAULT 0
);
CREATE TABLE catalog_art_host (
    hostname text PRIMARY KEY, next_attempt timestamptz NOT NULL
);
CREATE INDEX card_public_catalog_scan ON card(game_code,id) WHERE status='PUBLISHED';

-- A replaced or retracted source immediately loses all grants to display its old file.
CREATE FUNCTION clear_catalog_art_card() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM catalog_art_card WHERE card_id=OLD.id;
    RETURN NEW;
END $$;
CREATE TRIGGER catalog_art_source_changed AFTER UPDATE OF specs,status,game_code,legacy_key,number,original_name ON card
FOR EACH ROW WHEN ((OLD.specs->'images',OLD.specs->>'konami_id',OLD.status,OLD.game_code,OLD.legacy_key,OLD.number,OLD.original_name)
     IS DISTINCT FROM (NEW.specs->'images',NEW.specs->>'konami_id',NEW.status,NEW.game_code,NEW.legacy_key,NEW.number,NEW.original_name))
EXECUTE FUNCTION clear_catalog_art_card();

CREATE FUNCTION local_catalog_art(card_id bigint, image_url text) RETURNS text
LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT '/media/'||f.storage_key FROM catalog_art_file f JOIN catalog_art_card a ON a.file_id=f.id
        WHERE f.source_url=$2 AND a.card_id=$1 AND f.storage_key IS NOT NULL
$$;
