-- Independent passcode-to-CID reconciliation using Project Ignis LFLists (1c126747bf9f424d56df9ec2367e09051bb4872d)
-- and YAML Yugi (2355f8324797b38596dbf31eb21711f411299882). Effective dates/counts checked against official regional lists.
ALTER TABLE deck ADD COLUMN region text CHECK (region IS NULL OR (game_code='YUGIOH' AND region IN ('OCG','TCG')));
CREATE TABLE yugioh_limit_list (
    region text PRIMARY KEY CHECK (region IN ('OCG','TCG')),
    effective_on date NOT NULL,
    source_url text NOT NULL,
    file_sha256 text NOT NULL CHECK (file_sha256 ~ '^[a-f0-9]{64}$'),
    verified_on date NOT NULL,
    evidence_status text NOT NULL CHECK (evidence_status IN ('VERIFIED','CHANGED','UNAVAILABLE'))
);
CREATE TABLE yugioh_card_limit (
    region text NOT NULL REFERENCES yugioh_limit_list(region),
    konami_id integer NOT NULL CHECK (konami_id>0),
    max_copies smallint NOT NULL CHECK (max_copies BETWEEN 0 AND 2),
    PRIMARY KEY(region,konami_id)
);
CREATE INDEX card_yugioh_catalog_cid ON card ((specs->>'konami_id'))
    WHERE game_code='YUGIOH' AND starts_with(legacy_key,'catalog:YUGIOH:');

